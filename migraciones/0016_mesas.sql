-- El sorteo de mesas de una noche de cash.
--
-- Cuando llega mucha gente la noche se parte en dos mesas, y partirla a ojo acaba con
-- los cuatro que mejor juegan en la misma. Aquí se guarda cómo quedaron repartidos,
-- cada cuánto toca cambiar, el reloj de ese cambio y lo último que se contó de cada
-- quien, que es con lo que se vuelve a sortear a media noche.
--
-- Es una sola columna JSON y no una tabla aparte a propósito: no se consulta ni se
-- cruza con nada, se lee y se escribe entera, igual que la estructura de ciegas o el
-- reloj del torneo. En NULL están todas las partidas que nunca lo usaron, que son la
-- mayoría: la mesa de seis no se sortea.
ALTER TABLE partidas ADD COLUMN mesas TEXT;
